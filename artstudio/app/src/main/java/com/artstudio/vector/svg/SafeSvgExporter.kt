package com.artstudio.vector.svg

import com.artstudio.document.io.ConversionReport
import com.artstudio.document.io.ConversionWarning
import com.artstudio.document.model.ArtDocument
import com.artstudio.document.model.LayerNode
import com.artstudio.vector.*
import java.util.Locale

/**
 * Options configuring SVG export fidelity and text representation.
 */
data class SvgExportOptions(
    val rasterizeText: Boolean = false
)

/**
 * Serializes ArtStudio vector objects and layers into valid, standard SVG 1.1 documents.
 */
object SafeSvgExporter {

    fun exportObjects(
        objects: List<VectorObject>,
        width: Int,
        height: Int,
        title: String = "ArtStudio Vector Export",
        textLayers: List<LayerNode.TextLayer> = emptyList(),
        defs: List<String> = emptyList()
    ): String {
        val sb = StringBuilder()
        sb.appendLine("""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 $width $height" width="$width" height="$height">""")
        sb.appendLine("""  <!-- $title (Generated by ArtStudio Vector Engine) -->""")

        if (defs.isNotEmpty()) {
            sb.appendLine("  <defs>")
            for (d in defs) {
                sb.appendLine("    $d")
            }
            sb.appendLine("  </defs>")
        }

        for (obj in objects) {
            renderObjectToSvg(sb, obj, indent = "  ")
        }

        for (textLayer in textLayers) {
            renderTextToSvg(sb, textLayer, indent = "  ")
        }

        sb.appendLine("</svg>")
        return sb.toString()
    }

    fun exportDocument(
        document: ArtDocument,
        options: SvgExportOptions = SvgExportOptions()
    ): Pair<String, ConversionReport> {
        val warnings = mutableListOf<ConversionWarning>()
        val allLayers = document.allLayersFlat()

        val vectorObjects = mutableListOf<VectorObject>()
        val textLayers = mutableListOf<LayerNode.TextLayer>()

        for (layer in allLayers) {
            when (layer) {
                is LayerNode.VectorPathLayer -> {
                    vectorObjects.addAll(layer.allVectorObjects())
                }
                is LayerNode.TextLayer -> {
                    val textObj = layer.textObject
                    val fontRes = com.artstudio.text.FontEngine.resolveFont(textObj.fontFamily)
                    if (fontRes.fallbackOccurred) {
                        warnings.add(
                            ConversionWarning(
                                layerId = layer.id,
                                layerName = layer.name,
                                feature = "FONT_FALLBACK",
                                actionTaken = "Substituted font '${textObj.fontFamily}' with '${fontRes.resolvedFamily}'",
                                message = fontRes.report?.reason ?: "Font substituted."
                            )
                        )
                    }
                    if (options.rasterizeText) {
                        warnings.add(
                            ConversionWarning(
                                layerId = layer.id,
                                layerName = layer.name,
                                feature = "TEXT_RASTERIZATION",
                                actionTaken = "Rasterized text during export",
                                message = "Text layer was rasterized during SVG export."
                            )
                        )
                    } else {
                        textLayers.add(layer)
                    }
                }
                is LayerNode.RasterLayer -> {
                    warnings.add(
                        ConversionWarning(
                            layerId = layer.id,
                            layerName = layer.name,
                            feature = "RASTER_LAYER_DROPPED",
                            actionTaken = "Omitted raster bitmap layer from vector SVG export",
                            message = "Pure vector SVG export does not embed raster bitmap layers."
                        )
                    )
                }
                is LayerNode.LayerGroup -> {}
                is LayerNode.AdjustmentLayer -> {}
            }
        }

        // Export comic panels if present
        for (panel in document.comicPanels) {
            val vec = com.artstudio.comic.ComicGeometryEngine.panelToVectorObject(panel)
            if (vectorObjects.none { it.id == panel.id }) {
                vectorObjects.add(vec)
            }
        }

        // Export speech bubbles and dialogue text if present
        for (bubble in document.speechBubbles) {
            val vec = com.artstudio.comic.ComicGeometryEngine.createBubbleVectorObject(bubble)
            val dots = com.artstudio.comic.ComicGeometryEngine.generateThoughtDots(bubble)
            if (vectorObjects.none { it.id == bubble.id }) {
                vectorObjects.add(vec)
                vectorObjects.addAll(dots)
            }
            if (bubble.text.isNotBlank()) {
                val txtObj = com.artstudio.comic.ComicGeometryEngine.generateBubbleTextObject(bubble)
                val txtLayer = LayerNode.TextLayer(
                    id = "bubble_txt_${bubble.id.take(8)}",
                    name = "Bubble Text",
                    textObject = txtObj
                )
                textLayers.add(txtLayer)
            }
        }

        val patternDefs = document.screentones.map { tone ->
            com.artstudio.comic.ScreentoneEngine.generateSvgPatternDef(tone, "tone_${tone.id.take(8)}")
        }

        val svg = exportObjects(
            objects = vectorObjects,
            width = document.canvas.width,
            height = document.canvas.height,
            title = document.title,
            textLayers = textLayers,
            defs = patternDefs
        )

        return Pair(svg, ConversionReport("SVG", warnings))
    }

    private fun renderObjectToSvg(sb: StringBuilder, obj: VectorObject, indent: String) {
        val styleAttrs = formatStyle(obj.style)

        when (obj.shapeType) {
            VectorShapeType.RECTANGLE -> {
                val r = obj.rectData
                if (r != null) {
                    val rxAttr = if (r.rx > 0f) """ rx="${formatFloat(r.rx)}"""" else ""
                    val ryAttr = if (r.ry > 0f && r.ry != r.rx) """ ry="${formatFloat(r.ry)}"""" else ""
                    sb.appendLine("""$indent<rect x="${formatFloat(r.x)}" y="${formatFloat(r.y)}" width="${formatFloat(r.width)}" height="${formatFloat(r.height)}"$rxAttr$ryAttr$styleAttrs/>""")
                    return
                }
            }
            VectorShapeType.ELLIPSE -> {
                val el = obj.ellipseData
                if (el != null) {
                    if (el.rx == el.ry) {
                        sb.appendLine("""$indent<circle cx="${formatFloat(el.cx)}" cy="${formatFloat(el.cy)}" r="${formatFloat(el.rx)}"$styleAttrs/>""")
                    } else {
                        sb.appendLine("""$indent<ellipse cx="${formatFloat(el.cx)}" cy="${formatFloat(el.cy)}" rx="${formatFloat(el.rx)}" ry="${formatFloat(el.ry)}"$styleAttrs/>""")
                    }
                    return
                }
            }
            VectorShapeType.LINE -> {
                if (obj.anchors.size >= 2) {
                    val p1 = obj.anchors[0]
                    val p2 = obj.anchors[1]
                    sb.appendLine("""$indent<line x1="${formatFloat(p1.x)}" y1="${formatFloat(p1.y)}" x2="${formatFloat(p2.x)}" y2="${formatFloat(p2.y)}"$styleAttrs/>""")
                    return
                }
            }
            VectorShapeType.POLYLINE -> {
                if (obj.anchors.isNotEmpty()) {
                    val pts = obj.anchors.joinToString(" ") { "${formatFloat(it.x)},${formatFloat(it.y)}" }
                    sb.appendLine("""$indent<polyline points="$pts"$styleAttrs/>""")
                    return
                }
            }
            VectorShapeType.POLYGON -> {
                if (obj.anchors.isNotEmpty()) {
                    val pts = obj.anchors.joinToString(" ") { "${formatFloat(it.x)},${formatFloat(it.y)}" }
                    sb.appendLine("""$indent<polygon points="$pts"$styleAttrs/>""")
                    return
                }
            }
            VectorShapeType.BEZIER_PATH -> {
                // Handled as path below
            }
        }

        // Generic path
        val segments = obj.toSegments()
        if (segments.isEmpty()) return
        val pathD = formatPathData(segments)
        sb.appendLine("""$indent<path d="$pathD"$styleAttrs/>""")
    }

    private fun formatStyle(style: VectorStyle): String {
        val sb = StringBuilder()

        // Fill
        if (style.fillColor != null) {
            sb.append(""" fill="${formatColor(style.fillColor)}"""")
            if (style.fillRule == FillRule.EVEN_ODD) {
                sb.append(""" fill-rule="evenodd"""")
            }
        } else {
            sb.append(""" fill="none"""")
        }

        // Stroke
        if (style.strokeColor != null && style.strokeWidth > 0f) {
            sb.append(""" stroke="${formatColor(style.strokeColor)}"""")
            sb.append(""" stroke-width="${formatFloat(style.strokeWidth)}"""")
            if (style.strokeCap != StrokeCap.BUTT) {
                sb.append(""" stroke-linecap="${style.strokeCap.id}"""")
            }
            if (style.strokeJoin != StrokeJoin.MITER) {
                sb.append(""" stroke-linejoin="${style.strokeJoin.id}"""")
            }
        } else {
            sb.append(""" stroke="none"""")
        }

        // Opacity
        if (style.opacity < 1.0f) {
            sb.append(""" opacity="${formatFloat(style.opacity)}"""")
        }

        return sb.toString()
    }

    fun formatColor(color: Long): String {
        val a = ((color shr 24) and 0xFF).toInt()
        val r = ((color shr 16) and 0xFF).toInt()
        val g = ((color shr 8) and 0xFF).toInt()
        val b = (color and 0xFF).toInt()
        return if (a == 255) {
            String.format(Locale.ROOT, "#%02X%02X%02X", r, g, b)
        } else {
            String.format(Locale.ROOT, "#%02X%02X%02X%02X", r, g, b, a)
        }
    }

    fun formatPathData(segments: List<VectorSegment>): String {
        val sb = StringBuilder()
        for ((idx, seg) in segments.withIndex()) {
            if (idx > 0) sb.append(' ')
            when (seg) {
                is VectorSegment.MoveTo -> sb.append("M ${formatFloat(seg.x)} ${formatFloat(seg.y)}")
                is VectorSegment.LineTo -> sb.append("L ${formatFloat(seg.x)} ${formatFloat(seg.y)}")
                is VectorSegment.QuadTo -> sb.append("Q ${formatFloat(seg.x1)} ${formatFloat(seg.y1)} ${formatFloat(seg.x)} ${formatFloat(seg.y)}")
                is VectorSegment.CubicTo -> sb.append("C ${formatFloat(seg.x1)} ${formatFloat(seg.y1)} ${formatFloat(seg.x2)} ${formatFloat(seg.y2)} ${formatFloat(seg.x)} ${formatFloat(seg.y)}")
                is VectorSegment.Close -> sb.append("Z")
            }
        }
        return sb.toString()
    }

    fun renderTextToSvg(sb: StringBuilder, textLayer: LayerNode.TextLayer, indent: String = "  ") {
        val textObj = textLayer.textObject
        val colorHex = formatColor(textObj.textColor)
        val textAlpha = (((textObj.textColor shr 24) and 0xFF) / 255f) * textLayer.opacity
        val fillAttr = """ fill="$colorHex""""
        val opAttr = if (textAlpha < 0.999f) """ opacity="${formatFloat(textAlpha)}"""" else ""
        val fontRes = com.artstudio.text.FontEngine.resolveFont(textObj.fontFamily)
        val familyAttr = """ font-family="${fontRes.resolvedFamily}""""
        val sizeAttr = """ font-size="${formatFloat(textObj.fontSize)}""""
        val weightAttr = when (textObj.fontStyle) {
            com.artstudio.text.TextFontStyle.BOLD, com.artstudio.text.TextFontStyle.BOLD_ITALIC -> """ font-weight="bold""""
            else -> ""
        }
        val styleAttr = when (textObj.fontStyle) {
            com.artstudio.text.TextFontStyle.ITALIC, com.artstudio.text.TextFontStyle.BOLD_ITALIC -> """ font-style="italic""""
            else -> ""
        }
        val anchorAttr = when (textObj.alignment) {
            com.artstudio.text.TextAlignment.LEFT -> """ text-anchor="start""""
            com.artstudio.text.TextAlignment.CENTER -> """ text-anchor="middle""""
            com.artstudio.text.TextAlignment.RIGHT -> """ text-anchor="end""""
        }
        val decorAttr = when {
            textObj.isUnderline && textObj.isStrikeThrough -> """ text-decoration="underline line-through""""
            textObj.isUnderline -> """ text-decoration="underline""""
            textObj.isStrikeThrough -> """ text-decoration="line-through""""
            else -> ""
        }

        val lines = textObj.lines()
        val lineHeight = textObj.fontSize * textObj.lineSpacingMultiplier
        val baselineY = textObj.y + textObj.fontSize

        if (lines.size <= 1) {
            val escaped = escapeXml(textObj.text)
            sb.appendLine("""$indent<text x="${formatFloat(textObj.x)}" y="${formatFloat(baselineY)}"$familyAttr$sizeAttr$fillAttr$opAttr$weightAttr$styleAttr$anchorAttr$decorAttr>$escaped</text>""")
        } else {
            sb.appendLine("""$indent<text x="${formatFloat(textObj.x)}" y="${formatFloat(baselineY)}"$familyAttr$sizeAttr$fillAttr$opAttr$weightAttr$styleAttr$anchorAttr$decorAttr>""")
            for ((idx, line) in lines.withIndex()) {
                val dy = if (idx == 0) "0" else formatFloat(lineHeight)
                val escaped = escapeXml(line)
                sb.appendLine("""$indent  <tspan x="${formatFloat(textObj.x)}" dy="$dy">$escaped</tspan>""")
            }
            sb.appendLine("""$indent</text>""")
        }
    }

    private fun escapeXml(text: String): String {
        return text
            .replace("&", "&amp;")
            .replace("<", "&lt;")
            .replace(">", "&gt;")
            .replace("\"", "&quot;")
            .replace("'", "&apos;")
    }

    private fun formatFloat(v: Float): String {
        return if (v == v.toInt().toFloat()) {
            v.toInt().toString()
        } else {
            String.format(Locale.ROOT, "%.2f", v).trimEnd('0').trimEnd('.')
        }
    }
}
